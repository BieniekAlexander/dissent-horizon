#!/usr/bin/env python3
"""Write a POINT-SYMMETRIC copy of a scenario, leaving the authored one untouched.

WHY. The 2026-09-06 campaign measured a start-position advantage on `skirmish.tscn` that
FOLLOWS THE POSITION rather than the slot index (16 mirror seeds, then the same 16 with the
slot->start-point assignment exchanged). A biased map cannot be the substrate for a parameter
search: every A-vs-B comparison inherits whatever the map hands the side that happens to
start at the good corner.

THE AXIS. The map's own `Map.mirror_secondary_axis = 2` declares a 180 degree POINT
reflection (x, z) -> (-x, -z) -- the composition of the two diagonal reflections, which is
what "the map has a diagonal axis of symmetry" comes to in a play rectangle whose axes are
s = x + z and t = x - z. It is also the best fit by measurement: over the authored entities
the point reflection leaves a mean residual of 3.33 world units against 10.9 for a flip in Z
and 11.5 for a flip in X. So it is the author's declared intent AND the closest isometry the
map already nearly satisfies.

THE OPERATION. This script owns the SCENE half only:
  * authored nodes   -- every entity at x < 0 is kept and a reflected duplicate is emitted;
                        every entity at x > 0 is dropped.

THE TERRAIN HALF IS NOT DONE HERE ANY MORE, and that is a repair rather than a tidy-up. This
script used to symmetrize `TerrainData.heights` by rewriting the `.tres` text -- which is only
HALF the terrain. The brushable surface mesh (`<map>_surface.res`, `Map.terrain_source_mesh`)
carries the same heights as vertex Y and is what `Map.bake_terrain_from_mesh` reads; leaving it
alone meant the very next rebake in the editor replaced the symmetric heightfield with the flat
grid the mesh still held, and the map went flat. Both artifacts have to be written from one
computation, which needs Godot to read and write the mesh, so it lives in

    godot --headless --path . -s res://tools/terrain/make_symmetric_terrain.gd

which also asserts that re-baking is a NO-OP before it reports success. Run it FIRST; this
script refuses to run without its output. See CLAUDE.md §Regenerating data.
Two departures from the plain tool, both because the tool cannot know about them:
  * START POINTS are not duplicated -- the scene must hold exactly two. The first by sorted
    name is kept and the second is placed at its reflection, which moves StartPoint1_mirror
    by 2 world units. This is the whole point of the exercise: the two starts become exact
    images of one another.
  * An entity within SNAP_RADIUS of the origin (the reflection's only fixed point) is snapped
    ONTO the origin and kept once, rather than dropped for being on the wrong side. Only
    ShelterStructure3, at (1.0, 0.0), qualifies; dropping it would delete the map's centre
    feature to buy a symmetry that moving it one unit also buys.

Verify with `verify_symmetry.py`, which re-reads what this wrote and reports residuals.

    python3 tools/selfplay/results/make_symmetric_scenario.py
"""
import os
import re
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
SRC_TSCN = "scenes/scenarios/skirmish.tscn"
SRC_TRES = "resources/terrain/mesh_plateau_terrain.tres"
OUT_TSCN = "scenes/scenarios/skirmish_symmetric.tscn"
OUT_TRES = "resources/terrain/mesh_plateau_terrain_symmetric.tres"

## An entity nearer the origin than this is snapped onto it rather than dropped. The
## reflection's fixed point is a single point, so anything "on the axis" has to be moved
## exactly onto it to survive the operation at all.
SNAP_RADIUS = 2.0
## Half a cell. Below this an offset is authoring noise, not a side.
EPS = 0.01
START_POINT_GROUP = "start_position"


def read(path):
    return open(os.path.join(REPO, path), encoding="utf-8").read()


def write(path, text):
    with open(os.path.join(REPO, path), "w", encoding="utf-8") as handle:
        handle.write(text)
    print("wrote %s (%d bytes)" % (path, len(text)))


# --------------------------------------------------------------------------- terrain

OUT_MESH = "resources/terrain/mesh_plateau_terrain_symmetric_surface.res"


def require_terrain():
    """Refuse to write a scene whose terrain has not been generated by the Godot tool.

    Deliberately a HARD STOP rather than a fallback that writes the heights itself. A
    heightfield written here without its surface mesh is exactly the half-edit that broke
    this map once already (see the module docstring), and a convenience that can produce it
    is worse than no convenience at all.
    """
    missing = [p for p in (OUT_TRES, OUT_MESH)
               if not os.path.exists(os.path.join(REPO, p))]
    if missing:
        sys.exit(
            "missing generated terrain: %s\n"
            "run it first:\n"
            "  godot --headless --path . -s res://tools/terrain/make_symmetric_terrain.gd"
            % ", ".join(missing))
    print("terrain: using %s + %s" % (OUT_TRES, OUT_MESH))


# --------------------------------------------------------------------------- scene

def reflect_transform(values):
    """A Transform3D's 12 floats under a 180 degree rotation about Y.

    Godot lays them out as three basis COLUMNS (X, Y, Z axes) then the origin, so the
    rotation R = diag(-1, 1, -1) is applied to each of the four vectors in turn. The result
    is a proper rotation (determinant +1), not a mirroring, so a reflected structure is a
    structure someone turned around rather than an impossible left-handed copy.
    """
    out = []
    for k in range(4):
        x, y, z = values[k * 3:k * 3 + 3]
        out += [-x, y, -z]
    return out


def fmt_transform(values):
    return "transform = Transform3D(%s)" % ", ".join(_fmt(v) for v in values)


def symmetrize_scene():
    text = read(SRC_TSCN)
    lines = text.splitlines()

    # Split into a header (everything before the first [node) and a list of node blocks.
    first = next(i for i, l in enumerate(lines) if l.startswith("[node "))
    header = lines[:first]
    blocks, cur = [], None
    for line in lines[first:]:
        if line.startswith("[node "):
            cur = [line]
            blocks.append(cur)
        else:
            cur.append(line)

    def name_of(block):
        return re.match(r'^\[node name="([^"]+)"', block[0]).group(1)

    def origin_of(block):
        for line in block:
            m = re.match(r"^transform = Transform3D\(([^)]*)\)", line)
            if m:
                v = [float(x) for x in m.group(1).split(",")]
                return v
        return None

    def is_start_point(block):
        return START_POINT_GROUP in block[0]

    def is_entity(block):
        return 'parent="."' in block[0] and origin_of(block) is not None \
            and "DirectionalLight3D" not in block[0]

    kept, added, dropped, snapped = [], [], [], []
    starts = sorted([b for b in blocks if is_start_point(b)], key=name_of)
    assert len(starts) == 2, "expected exactly two start points, found %d" % len(starts)

    out_blocks = []
    for block in blocks:
        if is_start_point(block):
            continue                        # emitted below, as an exact pair
        if not is_entity(block):
            out_blocks.append(block)
            continue
        v = origin_of(block)
        x, z = v[9], v[11]
        if (x * x + z * z) ** 0.5 <= SNAP_RADIUS:
            v2 = list(v)
            v2[9], v2[11] = 0.0, 0.0
            out_blocks.append(_retransform(block, v2))
            snapped.append((name_of(block), x, z))
            continue
        if x > EPS:
            dropped.append(name_of(block))
            continue
        out_blocks.append(block)
        kept.append(name_of(block))
        mirror = _retransform(block, reflect_transform(v), rename=name_of(block) + "Sym")
        out_blocks.append(mirror)
        added.append(name_of(block) + "Sym")

    # The two start points, as exact images of one another.
    ref = origin_of(starts[0])
    out_blocks.append(_retransform(starts[0], ref))
    out_blocks.append(_retransform(starts[1], reflect_transform(ref)))

    header = [re.sub(r'^(\[gd_scene[^\]]*?) uid="[^"]*"', r"\1", l) for l in header]
    header = [l.replace('path="res://%s"' % SRC_TRES, 'path="res://%s"' % OUT_TRES)
              for l in header]
    header = [re.sub(r'^(\[ext_resource[^\]]*?) uid="[^"]*"(?=[^\]]*%s)'
                     % re.escape(OUT_TRES), r"\1", l) for l in header]

    body = []
    for block in out_blocks:
        # unique_id is per-scene bookkeeping; a duplicated one would collide, and Godot
        # mints a fresh one for any node that has none.
        head = re.sub(r"\s+unique_id=\d+", "", block[0])
        body.append(head)
        body += block[1:]
    write(OUT_TSCN, "\n".join(header + body).rstrip() + "\n")
    print("  kept %d entities, added %d reflections, dropped %d, snapped to origin: %s"
          % (len(kept), len(added), len(dropped), snapped))
    print("  dropped: %s" % ", ".join(dropped))


def _retransform(block, values, rename=None):
    out = []
    for line in block:
        if line.startswith("transform = Transform3D("):
            out.append(fmt_transform(values))
        elif rename and line.startswith("[node "):
            out.append(re.sub(r'^\[node name="[^"]+"', '[node name="%s"' % rename, line))
        else:
            out.append(line)
    if rename and not any(l.startswith("transform") for l in out):
        out.insert(1, fmt_transform(values))
    return out


if __name__ == "__main__":
    require_terrain()
    symmetrize_scene()
